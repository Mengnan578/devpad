ITERM_FIND_SESSION = '''
    tell application "iTerm"
        repeat with i from 1 to (count of windows)
            try
                set s to current session of window i
                if (tty of s as text) is "__TTY__" then return "hit"
            end try
        end repeat
        return "miss"
    end tell
'''


class ItermDriver(Driver):
    name = "iterm"

    def available(self) -> tuple[bool, str]:
        if not app_present("iTerm"):
            return False, "iTerm.app not installed"
        # A window-scoped read is the honest test: `get version` is answered by
        # macOS itself and succeeds even when scripting iTerm is forbidden, so it
        # would report a broken setup as healthy.
        rc, out, err = osascript('tell application "iTerm" to get count of windows', timeout=15)
        if rc == 0:
            return True, f"scripting allowed ({out} window(s) open)"
        return False, (err or f"rc={rc}") + _permission_hint(err)

    def plan(self, spec: RunnerSpec, runner: Path) -> list[str]:
        return [
            'tell application "iTerm" to create window with default profile',
            "read the new session's tty path (the stable handle; id is not dependable)",
            "poll until the session reports is processing = false",
            f'write text "exec {runner}" into that session',
            'handle: {"driver": "iterm", "tty": "/dev/ttysNNN"}',
        ]

    def spawn(self, spec: RunnerSpec, runner: Path) -> dict | None:
        create = """
        tell application "iTerm"
            activate
            set w to (create window with default profile)
            tell current session of w
                return (tty of it as text)
            end tell
        end tell
        """
        rc, tty, err = osascript(create)
        if rc != 0 or not tty:
            print(f"    !! iterm: cannot create window: {(err or f'rc={rc}')}{_permission_hint(err)}")
            return None

        # Without this wait the command is dropped on the floor.
        ready = f'''
        tell application "iTerm"
            repeat 40 times
                repeat with i from 1 to (count of windows)
                    try
                        set s to current session of window i
                        if (tty of s as text) is "{tty}" then
                            if (is processing of s) is false then return "ready"
                        end if
                    end try
                end repeat
                delay 0.1
            end repeat
            return "timeout"
        end tell
        '''
        rc, state, err = osascript(ready, timeout=20)
        if state != "ready":
            print(f"    ~ iterm: session not idle yet ({state or err}); writing anyway")

        write = f'''
        tell application "iTerm"
            repeat with i from 1 to (count of windows)
                try
                    set s to current session of window i
                    if (tty of s as text) is "{tty}" then
                        tell s to write text "exec {runner}"
                        return "written"
                    end if
                end try
            end repeat
            return "not-found"
        end tell
        '''
        rc, result, err = osascript(write, timeout=30)
        if rc == 0 and result == "written":
            return {"driver": self.name, "tty": tty}
        print(f"    !! iterm: cannot write to window: {(result + ' ' + err).strip()}")
        return None

    def close(self, handle: dict) -> bool:
        tty = handle.get("tty")
        if not tty:
            return False
        script = f'''
        tell application "iTerm"
            repeat with i from 1 to (count of windows)
                try
                    set s to current session of window i
                    if (tty of s as text) is "{tty}" then
                        close window i
                        return "closed"
                    end if
                end try
            end repeat
            return "not-found"
        end tell
        '''
        rc, out, _ = osascript(script, timeout=25)
        # "not-found" is success: killing the service's process group usually makes
        # the window close itself, so by now there is nothing left to close.
        return rc == 0 and out in ("closed", "not-found")


