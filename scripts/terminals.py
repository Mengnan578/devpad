class AppleTerminalDriver(Driver):
    name = "apple-terminal"

    def available(self) -> tuple[bool, str]:
        if not app_present("Terminal"):
            return False, "Terminal.app not found"
        rc, out, err = osascript('tell application "Terminal" to get count of windows', timeout=15)
        if rc == 0:
            return True, f"scripting allowed ({out} window(s) open)"
        return False, (err or f"rc={rc}") + _permission_hint(err)

    def plan(self, spec: RunnerSpec, runner: Path) -> list[str]:
        return [
            f'tell application "Terminal" to do script "exec {runner}"',
            f"set the tab's custom title to {spec.title!r} (the only stable handle)",
            'handle: {"driver": "apple-terminal", "title": ...}',
        ]

    def spawn(self, spec: RunnerSpec, runner: Path) -> dict | None:
        script = f'''
        tell application "Terminal"
            activate
            set t to do script "exec {runner}"
            set custom title of t to {json.dumps(spec.title)}
            return "spawned"
        end tell
        '''
        rc, out, err = osascript(script)
        if rc == 0 and out == "spawned":
            return {"driver": self.name, "title": spec.title}
        print(f"    !! apple-terminal: {(err or f'rc={rc}')}{_permission_hint(err)}")
        return None

    def close(self, handle: dict) -> bool:
        title = handle.get("title")
        if not title:
            return False
        script = f'''
        tell application "Terminal"
            repeat with i from 1 to (count of windows)
                try
                    set t to selected tab of window i
                    if (custom title of t) is {json.dumps(title)} then
                        close window i saving no
                        return "closed"
                    end if
                end try
            end repeat
            return "not-found"
        end tell
        '''
        rc, out, _ = osascript(script, timeout=25)
        # "not-found" is success: killing the service's process group usually makes
        # the window close itself, so by now there is nothing left to close.
        return rc == 0 and out in ("closed", "not-found")


