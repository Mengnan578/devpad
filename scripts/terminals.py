class Driver:
    """A way to put a service on screen."""

    name = "base"
    supports_close = True
    # POSIX drivers execute a generated shell script; Windows drivers re-enter the
    # engine with `run`, so they do not need one.
    needs_runner = True

    def available(self) -> tuple[bool, str]:
        raise NotImplementedError

    def spawn(self, spec: RunnerSpec, runner: Path) -> dict | None:
        raise NotImplementedError

    def close(self, handle: dict) -> bool:
        return False

    def plan(self, spec: RunnerSpec, runner: Path) -> list[str]:
        """The exact actions spawn() would take, for --dry-run and for tests."""
        raise NotImplementedError


def osascript(script: str, timeout: int = 40) -> tuple[int, str, str]:
    """Run AppleScript. Returns (rc, stdout, stderr) and never raises."""
    try:
        proc = subprocess.run(
            ["osascript", "-e", script],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        # A first-run automation prompt appears outside the process; a timeout here
        # almost always means someone is looking at that dialog.
        return 124, "", "osascript timed out — an automation permission dialog may be waiting"
    except OSError as exc:
        return 127, "", str(exc)
    return (
        proc.returncode,
        proc.stdout.decode("utf-8", "replace").strip(),
        proc.stderr.decode("utf-8", "replace").strip(),
    )


def app_present(name: str) -> bool:
    """Terminal.app ships under /System/Applications/Utilities, so check there too."""
    roots = [
        f"/Applications/{name}.app",
        f"/System/Applications/{name}.app",
        f"/System/Applications/Utilities/{name}.app",
        os.path.expanduser(f"~/Applications/{name}.app"),
    ]
    return any(Path(p).is_dir() for p in roots)


def _permission_hint(stderr: str) -> str:
    if "-10004" in stderr or "not allowed" in stderr.lower() or "权限" in stderr:
        return (
            " — this host is not allowed to send Apple Events. Either grant it under "
            "System Settings → Privacy & Security → Automation, or use "
            "`terminal.driver: command-file`, which does not need that permission"
        )
    return ""


