class CommandFileDriver(Driver):
    """Hand a .command to `open`. Needs no Automation permission, so it works even
    where AppleScript is forbidden — but it yields no window handle, so `close()`
    cannot close the window itself."""

    name = "command-file"
    supports_close = False

    def available(self) -> tuple[bool, str]:
        if sys.platform != "darwin":
            return False, "macOS only"
        if not shutil.which("open"):
            return False, "open(1, encoding='utf-8') not found"
        return True, "uses open(1, encoding='utf-8'); no Automation permission required"

    def plan(self, spec: RunnerSpec, runner: Path) -> list[str]:
        return [
            f"write runner to {runner}",
            f"open -a Terminal {runner}",
            "handle: {\"driver\": \"command-file\"} — no window handle, close is not possible",
        ]

    def spawn(self, spec: RunnerSpec, runner: Path) -> dict | None:
        try:
            proc = subprocess.run(
                ["open", "-a", "Terminal", str(runner)],
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                timeout=30,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            print(f"    !! command-file: {exc}")
            return None
        if proc.returncode != 0:
            print(f"    !! command-file: open failed: {proc.stdout.decode('utf-8', 'replace').strip()}")
            return None
        return {"driver": self.name, "runner": str(runner)}

    def close(self, handle: dict) -> bool:
        # There is no addressable window; the caller stops the process group instead
        # and the window is closed by the user. Reported honestly rather than faked.
        return False


# ---------------------------------------------------------------------------
# tmux  (persistent sessions; the cleanest lifecycle of all)
# ---------------------------------------------------------------------------


class TmuxDriver(Driver):
    name = "tmux"

    def _exe(self) -> str | None:
        return shutil.which("tmux")

    def available(self) -> tuple[bool, str]:
        exe = self._exe()
        if not exe:
            return False, "tmux not installed"
        return True, exe

    def plan(self, spec: RunnerSpec, runner: Path) -> list[str]:
        return [
            f"tmux new-session -d -s devpad-{spec.title} -c {spec.cwd} 'exec {runner}'",
            "open a terminal and attach it to that session",
            f'handle: {{"driver": "tmux", "session": "devpad-{spec.title}"}}',
        ]

    def spawn(self, spec: RunnerSpec, runner: Path) -> dict | None:
        exe = self._exe()
        if not exe:
            print("    !! tmux: not installed")
            return None
        session = f"devpad-{spec.title}"
        subprocess.run([exe, "kill-session", "-t", session], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        proc = subprocess.run(
            [exe, "new-session", "-d", "-s", session, "-c", str(spec.cwd), f"exec {runner}"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        if proc.returncode != 0:
            print(f"    !! tmux: {proc.stdout.decode('utf-8', 'replace').strip()}")
            return None
        handle = {"driver": self.name, "session": session}
        # Attach a visible window when one is available; the session survives anyway.
        if app_present("iTerm"):
            rc, tty, _ = osascript(
                """
                tell application "iTerm"
                    activate
                    set w to (create window with default profile)
                    set s to current session of w
                    return (tty of s as text)
                end tell
                """
            )
            if rc == 0 and tty:
                time.sleep(0.4)
                osascript(
                    f'''
                    tell application "iTerm"
                        repeat with i from 1 to (count of windows)
                            try
                                set s to current session of window i
                                if (tty of s as text) is "{tty}" then
                                    tell s to write text "tmux attach -t {session}"
                                    return "ok"
                                end if
                            end try
                        end repeat
                    end tell
                    ''',
                    timeout=20,
                )
                handle["tty"] = tty
        return handle

    def close(self, handle: dict) -> bool:
        exe = self._exe()
        session = handle.get("session")
        if not exe or not session:
            return False
        proc = subprocess.run([exe, "kill-session", "-t", session], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return proc.returncode == 0


