#!/usr/bin/env python3
"""Terminal drivers: open a visible window and run a service inside it.

This module is the answer to the actual pain: *the log has to be visible, in a
window I can scroll, select and copy from* — not trapped in an agent's buffer.

Every design choice here comes from something that was verified on a real machine,
not assumed. The failures were specific and are documented so they are not
re-introduced:

  * `write text` issued immediately after `create window` is SILENTLY LOST. The
    window opens, does nothing, and vanishes. The driver must wait for the session
    to become idle before typing.
  * iTerm has no usable `sessions of window` collection (-1728), and `id of window`
    is not dependable. Session access is by window index, wrapped in `try`.
  * Terminal.app lives in /System/Applications/Utilities, not /Applications.
  * A window opened from an app icon does not inherit the user's shell profile, so
    the service must run through a LOGIN shell or `node`/`python3` resolve wrongly.

The interface is small on purpose, and every driver implements `plan()` so the
behaviour can be tested without opening a single window.
"""

from __future__ import annotations

import json
import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

_SCRIPT_DIR = Path(__file__).resolve().parent
if str(_SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPT_DIR))

import sysenv  # noqa: E402

# ---------------------------------------------------------------------------
# shared runner generation
# ---------------------------------------------------------------------------


def login_shell() -> str:
    """The user's login shell. On Windows there is no equivalent: `cmd` is used."""
    shell = sysenv.login_shell()
    return shell or (os.environ.get("COMSPEC") or "cmd.exe")


class RunnerSpec:
    """Everything needed to describe one service's window."""

    def __init__(
        self,
        title: str,
        cwd: Path,
        command: str,
        hold: bool = True,
        env: dict | None = None,
        pid_file: Path | None = None,
        log_path: Path | None = None,
        service_name: str | None = None,
        project_root: Path | None = None,
    ):
        self.title = title
        self.cwd = cwd
        self.command = command
        self.hold = hold
        self.env = env or {}
        self.pid_file = pid_file
        # When set, the window's output is also recorded here via `script(1)`, so
        # an agent can read what is on screen without screen-scraping the terminal.
        self.log_path = log_path
        # Windows needs to re-enter the engine to run one service in a window; these
        # two tell it which service and which project to load.
        self.service_name = service_name
        self.project_root = project_root

    def as_dict(self) -> dict:
        return {
            "title": self.title,
            "cwd": str(self.cwd),
            "command": self.command,
            "hold": self.hold,
            "env": self.env,
            "pid_file": str(self.pid_file) if self.pid_file else None,
            "log_path": str(self.log_path) if self.log_path else None,
        }


def _teepty_path() -> Path | None:
    """Locate teepty.py next to this module (it ships in the same directory)."""
    candidate = Path(__file__).resolve().parent / "teepty.py"
    return candidate if candidate.is_file() else None


def render_runner(spec: RunnerSpec) -> str:
    """Build the wrapper script the window executes.

    Two requirements are non-negotiable and live here:

      1. the command runs through the user's LOGIN shell, because `nvm`/`pyenv`/
         `conda` only exist in their profile — otherwise the window gets a different
         (or missing) `node`/`python3` than their own terminal;
      2. the exit code is printed and the window is held open afterwards, so a
         crashed service's log is still on screen to read and copy.

    The runner also writes its own pid, so the parent can track and stop a process
    it did not spawn directly.
    """
    shell = login_shell()
    lines = [
        "#!/bin/sh",
        "# Generated by devpad. Safe to delete; it is recreated on every start.",
        f"DEVPAD_TITLE={shlex.quote(spec.title)}",
        f"cd {shlex.quote(str(spec.cwd))} || exit 1",
    ]
    for key, value in spec.env.items():
        if _valid_env_name(key):
            lines.append(f"export {key}={shlex.quote(str(value))}")
    if spec.pid_file:
        lines.append(f"printf '%s\\n' \"$$\" > {shlex.quote(str(spec.pid_file))}")

    quoted_cmd = shlex.quote(spec.command)
    tee = _teepty_path()
    if spec.log_path and tee:
        # teepty allocates a pty and copies the output to both the terminal and the
        # log, live. Plain redirection would kill TTY behaviour, and `script(1)` on
        # macOS buffers until exit — an empty log exactly while the server runs.
        execute = (
            f"{shlex.quote(sys.executable)} {shlex.quote(str(tee))} "
            f"{shlex.quote(str(spec.log_path))} {shell} -lc {quoted_cmd}"
        )
    else:
        execute = f"{shell} -lc {quoted_cmd}"

    lines += [
        "printf '\\n\\033[1m── %s ──\\033[0m\\n' \"$DEVPAD_TITLE\"",
        "printf '\\033[2mcwd: %s\\033[0m\\n' \"$(pwd)\"",
        f"printf '\\033[2mcmd: %s\\033[0m\\n' {shlex.quote(spec.command)}",
        "printf '\\n'",
        execute,
        "devpad_code=$?",
        "printf '\\n\\033[1m── %s exited with code %s ──\\033[0m\\n' \"$DEVPAD_TITLE\" \"$devpad_code\"",
    ]
    if spec.hold:
        lines.append("printf 'Press Enter to close this window... '")
        lines.append("read -r _")
    return "\n".join(lines) + "\n"


def _valid_env_name(name: str) -> bool:
    return bool(name) and (name[0].isalpha() or name[0] == "_") and all(c.isalnum() or c == "_" for c in name)


def write_runner(spec: RunnerSpec, runner_dir: Path) -> Path:
    runner_dir.mkdir(parents=True, exist_ok=True)
    safe = "".join(c if (c.isalnum() or c in "-_.") else "_" for c in spec.title)
    path = runner_dir / f"{safe}.command"
    path.write_text(render_runner(spec), encoding="utf-8")
    path.chmod(0o755)
    return path


